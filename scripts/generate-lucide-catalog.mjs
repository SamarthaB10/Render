import { cpSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const lucideRoot = path.join(root, "node_modules", "lucide-static");
const lucidePackage = JSON.parse(readFileSync(path.join(lucideRoot, "package.json"), "utf8"));
const info = JSON.parse(readFileSync(path.join(lucideRoot, "font", "info.json"), "utf8"));
const names = Object.keys(info).sort();

const aliases = {
  "backward.end.fill": "skip-back",
  "forward.end.fill": "skip-forward",
  "pause.fill": "pause",
  "play.fill": "play"
};

writeFileSync(path.join(root, "packages", "sdk", "src", "icon-catalog.ts"), `${[
  `// Generated by scripts/generate-lucide-catalog.mjs from lucide-static@${lucidePackage.version}.`,
  `export const SDK_ICON_NAMES = ${JSON.stringify(names)} as const;`,
  "export type SdkIconName = typeof SDK_ICON_NAMES[number];",
  `const ICON_ALIASES: Readonly<Record<string, SdkIconName>> = Object.freeze(${JSON.stringify(aliases)});`,
  "const ICON_NAMES = new Set<string>(SDK_ICON_NAMES);",
  "export function canonicalIconName(name: string): SdkIconName | null {",
  "  const canonical = ICON_ALIASES[name] ?? name;",
  "  return ICON_NAMES.has(canonical) ? canonical as SdkIconName : null;",
  "}",
  ""
].join("\n")}`);

const nativeCatalog = Object.fromEntries(names.map((name) => [name, Number(info[name].unicode.match(/\d+/)?.[0])]));
const resourceRoot = path.join(root, "Sources", "RenderHost", "LucideResources");
mkdirSync(resourceRoot, { recursive: true });
writeFileSync(path.join(resourceRoot, "catalog.json"), `${JSON.stringify({ version: lucidePackage.version, icons: nativeCatalog })}\n`);
cpSync(path.join(lucideRoot, "font", "lucide.ttf"), path.join(resourceRoot, "lucide.ttf"));
cpSync(path.join(lucideRoot, "LICENSE"), path.join(resourceRoot, "LICENSE"));

console.log(`generated ${names.length} Lucide icons`);
